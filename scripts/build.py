"""Deterministic, dependency-free bundler. Python 3.9+; never downloads code."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def release_version(root: Path = ROOT) -> str:
    version = json.loads((root / "version.json").read_text(encoding="utf-8-sig"))["version"]
    if not isinstance(version, str) or not re.fullmatch(r"\d+\.\d+\.\d+(?:-[\w.]+)?", version):
        raise ValueError("Invalid release version")
    return version


def sources(root: Path = ROOT) -> dict[str, str]:
    modules: dict[str, str] = {}
    for group in ("client", "shared"):
        for path in sorted((root / "src" / group).glob("*.luau")):
            if path.name.endswith(".client.luau"):
                continue
            modules[f"{group}/{path.stem}"] = path.read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    modules["config/ClientPolicy"] = (root / "config" / "ClientPolicy.luau").read_text(encoding="utf-8-sig").replace("\r\n", "\n")
    for name, source in modules.items():
        if not re.search(r"return\s+function\s*\(", source):
            raise ValueError(f"Module must export factory: {name}")
        for dependency in re.findall(r'\bimport\("([^"]+)"\)', source):
            if dependency not in modules:
                raise ValueError(f"Missing dependency {dependency} in {name}")
    required = {"client/ClientController", "client/AimAssist", "client/ESPManager",
                "client/FlightController", "client/SpeedController", "client/HealthDiagnostics", "shared/UIManager"}
    if not required.issubset(modules):
        raise ValueError(f"Missing required modules: {sorted(required-set(modules))}")
    return modules


def bundle(modules: dict[str, str], version: str | None = None) -> str:
    version = version or release_version()
    lines = [f"-- VW MENU {version} | generated by scripts/build.py | review sources before execution",
             "-- No automatic module downloads; optional version check reads metadata only.",
             "local factories, cache, loading = {}, {}, {}"]
    for name in sorted(modules):
        lines.extend([f'-- BEGIN {name}', f'factories["{name}"] = (function()', modules[name].rstrip(), "end)()"])
    lines.extend(['local function import(name)', '    if cache[name] ~= nil then return cache[name] end',
                  '    assert(factories[name], "VW missing module: " .. name)',
                  '    assert(not loading[name], "VW circular dependency: " .. name)',
                  '    loading[name] = true', '    local value = factories[name](import)',
                  '    assert(value ~= nil, "VW empty module: " .. name)',
                  '    cache[name] = value; loading[name] = nil', '    return value', 'end',
                  'return import("client/ClientController").Start()', ''])
    return "\n".join(lines)


def build(root: Path = ROOT) -> dict:
    modules = sources(root)
    version = release_version(root)
    output = bundle(modules, version).encode("utf-8")
    dist = root / "dist"
    dist.mkdir(exist_ok=True)
    (dist / "VWMenu.luau").write_bytes(output)
    manifest = {"version": version, "protocol": 1,
                "bundle": "dist/VWMenu.luau", "sha256": hashlib.sha256(output).hexdigest(),
                "bytes": len(output), "modules": sorted(modules)}
    (dist / "manifest.json").write_bytes((json.dumps(manifest, indent=2) + "\n").encode("utf-8"))
    return manifest


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.parse_args()
    result = build()
    print(f'Built {result["bundle"]}: {len(result["modules"])} modules, {result["bytes"]} bytes, sha256 {result["sha256"]}')
